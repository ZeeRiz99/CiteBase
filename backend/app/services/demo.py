"""The labeled demo seed: one verified demo account whose workspace holds the fictional samples.

This is the only place demo data enters the product (see CLAUDE.md). Documents go through the
normal upload path (validation, storage, ingestion jobs, audit), so the demo behaves exactly like
a real workspace. Running it twice does nothing the second time.
"""

from __future__ import annotations

import secrets
from dataclasses import dataclass
from pathlib import Path

from fastapi import UploadFile
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import CurrentContext
from app.core.config import Settings
from app.core.errors import AppError
from app.core.rate_limit import DisabledRateLimiter
from app.db.ids import uuid7
from app.ingestion.validation import ALLOWED_TYPES
from app.models import Role
from app.providers.storage import Storage
from app.repositories import users as users_repo
from app.repositories import workspaces as ws_repo
from app.services.auth import AuthService
from app.services.documents import DocumentService

DEMO_EMAIL = "demo@example.com"
DEMO_NAME = "Demo User"
DEMO_WORKSPACE = "Northwind Outfitters (demo)"


@dataclass
class SeedResult:
    created: bool
    email: str
    password: str | None  # only when generated by this run
    uploaded: list[str]
    rejected: dict[str, str]


def sample_files(folder: Path) -> list[Path]:
    """Every uploadable file in the folder (the README and other types are skipped)."""
    return sorted(
        p
        for p in folder.iterdir()
        if p.is_file() and p.suffix.lower() in ALLOWED_TYPES and p.name != "README.txt"
    )


async def seed_demo(
    db: AsyncSession,
    settings: Settings,
    storage: Storage,
    files: list[Path],
    *,
    email: str = DEMO_EMAIL,
    password: str | None = None,
) -> SeedResult:
    if await users_repo.get_user_by_email(db, email.lower()):
        return SeedResult(False, email, None, [], {})
    generated = password is None
    password = password or secrets.token_urlsafe(12)

    auth = AuthService(db, settings, DisabledRateLimiter())
    user, workspace_id = await auth.create_demo_account(
        full_name=DEMO_NAME, email=email, password=password, workspace_name=DEMO_WORKSPACE
    )
    workspace = await ws_repo.get_workspace(db, workspace_id)
    assert workspace is not None
    ctx = CurrentContext(
        user=user, workspace=workspace, role=Role.owner, session_id=uuid7(), family_id=uuid7()
    )
    documents = DocumentService(db, settings, storage, ctx)

    uploaded: list[str] = []
    rejected: dict[str, str] = {}
    for path in files:
        with path.open("rb") as handle:
            try:
                await documents.upload(UploadFile(file=handle, filename=path.name), None)
                uploaded.append(path.name)
            except AppError as exc:  # rejected before anything is written: report, keep going
                rejected[path.name] = exc.message
    return SeedResult(True, email, password if generated else None, uploaded, rejected)
