"""File storage behind one interface. Local disk now; an S3-compatible backend arrives in V2.

Keys are generated by the server (`<workspace_id>/<uuid>`), never derived from user input,
so path traversal is impossible by construction. `_path` still rejects anything odd.
"""

from __future__ import annotations

import os
import re
import shutil
import uuid
from pathlib import Path
from typing import BinaryIO, Protocol

from app.core.config import Settings
from app.db.ids import uuid7

_KEY_RE = re.compile(r"^[0-9a-f-]{36}/[0-9a-f-]{36}$")


class Storage(Protocol):
    def new_key(self, workspace_id: uuid.UUID) -> str: ...
    def temp_path(self) -> Path: ...
    def commit_temp(self, temp: Path, key: str) -> None: ...
    def open(self, key: str) -> BinaryIO: ...
    def local_path(self, key: str) -> Path: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        (self.root / "tmp").mkdir(parents=True, exist_ok=True)

    def new_key(self, workspace_id: uuid.UUID) -> str:
        return f"{workspace_id}/{uuid7()}"

    def _path(self, key: str) -> Path:
        if not _KEY_RE.fullmatch(key):
            raise ValueError("invalid storage key")
        return self.root / key

    def temp_path(self) -> Path:
        return self.root / "tmp" / f"{uuid7()}.part"

    def commit_temp(self, temp: Path, key: str) -> None:
        target = self._path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        os.replace(temp, target)

    def open(self, key: str) -> BinaryIO:
        return self._path(key).open("rb")

    def local_path(self, key: str) -> Path:
        return self._path(key)

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete_workspace(self, workspace_id: uuid.UUID) -> None:
        shutil.rmtree(self.root / str(workspace_id), ignore_errors=True)


def build_storage(settings: Settings) -> LocalStorage:
    return LocalStorage(settings.storage_dir)
